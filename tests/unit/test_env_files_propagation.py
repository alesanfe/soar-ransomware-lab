"""BUG-062: credential rotation must propagate to the `.env.container` snapshot.

Init scripts (``init_shuffle_webhook`` via ``es_fixes``, ``init_thehive``,
``reset_cortex``) rotate API keys into ``.env.full``. ``.env.container`` is a
generated snapshot of ``.env.full`` mounted read-only into the API container;
when it goes stale, in-container consumers (E2E tests, keepalive) authenticate
with the OLD key and get 401s.
"""

import scripts.setup.shuffle_workflow.config as wf_config
from scripts.setup import env_files, init_thehive, reset_cortex
from scripts.setup.shuffle_workflow import es_fixes

ENV_BODY = (
    "THEHIVE_API_KEY=old-hive\n"
    "CORTEX_API_KEY=old-cortex\n"
    "SHUFFLE_DEFAULT_APIKEY=old-shuffle\n"
    "OTHER=keep\n"
)


def _seed(tmp_path):
    env_full = tmp_path / ".env.full"
    env_full.write_text(ENV_BODY, encoding="utf-8")
    env_container = tmp_path / ".env.container"
    env_container.write_text(
        "# Generated by build_local_env.py — do not edit.\n" + ENV_BODY, encoding="utf-8"
    )
    return env_full, env_container


class TestUpdateEnvFilesHelper:
    """The shared helper writes every rotated key into both files."""

    def test_updates_both_files(self, tmp_path):
        env_full, env_container = _seed(tmp_path)
        written = env_files.update_env_files(
            {"SHUFFLE_DEFAULT_APIKEY": "new-shuffle"}, env_file=env_full
        )
        assert env_container in written
        assert "SHUFFLE_DEFAULT_APIKEY=new-shuffle" in env_full.read_text(encoding="utf-8")
        assert "SHUFFLE_DEFAULT_APIKEY=new-shuffle" in env_container.read_text(encoding="utf-8")
        assert "OTHER=keep" in env_container.read_text(encoding="utf-8")

    def test_appends_missing_key(self, tmp_path):
        env_full, env_container = _seed(tmp_path)
        env_files.update_env_files({"NEW_KEY": "v1"}, env_file=env_full)
        assert "NEW_KEY=v1" in env_full.read_text(encoding="utf-8")
        assert "NEW_KEY=v1" in env_container.read_text(encoding="utf-8")

    def test_missing_container_file_is_not_created(self, tmp_path):
        env_full = tmp_path / ".env.full"
        env_full.write_text(ENV_BODY, encoding="utf-8")
        written = env_files.update_env_files({"K": "v"}, env_file=env_full)
        assert written == [env_full]
        assert not (tmp_path / ".env.container").exists()

    def test_missing_env_file_returns_empty(self, tmp_path):
        assert env_files.update_env_files({"K": "v"}, env_file=tmp_path / ".env.full") == []


class TestRotationCallSites:
    """Every rotation path must propagate — not just one."""

    def test_es_fixes_propagates(self, tmp_path, monkeypatch):
        env_full, env_container = _seed(tmp_path)
        monkeypatch.setattr(wf_config, "ENV_FILE", str(env_full))
        es_fixes.update_env_file("SHUFFLE_DEFAULT_APIKEY", "new-shuffle")
        assert "new-shuffle" in env_container.read_text(encoding="utf-8")

    def test_init_thehive_propagates(self, tmp_path, monkeypatch):
        env_full, env_container = _seed(tmp_path)
        monkeypatch.setattr(init_thehive, "ENV_FILE", str(env_full))
        init_thehive.update_env_file("new-hive")
        assert "THEHIVE_API_KEY=new-hive" in env_container.read_text(encoding="utf-8")

    def test_reset_cortex_propagates(self, tmp_path, monkeypatch):
        env_full, env_container = _seed(tmp_path)
        monkeypatch.setattr(reset_cortex, "ENV_FILE", str(env_full))
        reset_cortex.update_env_file("new-cortex")
        assert "CORTEX_API_KEY=new-cortex" in env_container.read_text(encoding="utf-8")
