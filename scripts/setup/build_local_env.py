#!/usr/bin/env python3
"""Build the local ``.env`` for Docker Desktop from ``.env.full``.

Copies every variable except ``RUNTIME_DIR``, ``REPORTS_DIR`` and
``ARTIFACTS_DIR``, then appends the three directory variables resolved to
absolute, POSIX-style paths so Docker for Windows can bind-mount them.

Extracted from a ``python -c`` one-liner in ``Makefile.win`` whose quoting
broke when GNU Make picked a POSIX shell (``sh.exe``) from ``PATH``.
"""

from __future__ import annotations

import pathlib
import sys

SOURCE_ENV = ".env.full"
TARGET_ENV = ".env"
CONTAINER_ENV = ".env.container"
MANAGED_KEYS = ("RUNTIME_DIR=", "REPORTS_DIR=", "ARTIFACTS_DIR=")


def _posix_abs(dirname: str) -> str:
    """Return the absolute path of *dirname* with forward slashes."""
    return str(pathlib.Path(dirname).resolve()).replace("\\", "/")


def main() -> int:
    src = pathlib.Path(SOURCE_ENV)
    if not src.exists():
        print(f"ERROR: {SOURCE_ENV} not found — run generate_secrets.py first")
        return 1

    lines = [
        line
        for line in src.read_text(encoding="utf-8").splitlines()
        if not any(line.startswith(key) for key in MANAGED_KEYS)
    ]
    lines.append(f"ARTIFACTS_DIR={_posix_abs('runtime')}")
    lines.append(f"RUNTIME_DIR={_posix_abs('runtime')}")
    lines.append(f"REPORTS_DIR={_posix_abs('reports')}")

    pathlib.Path(TARGET_ENV).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {TARGET_ENV} ({len(lines)} variables)")

    # `.env.container` is the runtime-facing snapshot mounted read-only into
    # the API container. It intentionally excludes the absolute host paths
    # above so the container never sees host filesystem locations, and it
    # keeps `.env.full` itself out of the container (SOAR-018).
    header = (
        "# Generated by build_local_env.py — do not edit.\n"
        "# Container-facing subset of .env.full (host paths stripped).\n"
    )
    pathlib.Path(CONTAINER_ENV).write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {CONTAINER_ENV} ({len(lines)} variables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
