#!/usr/bin/env python3
"""MNT-01: generate docs/SCRIPTS-MANIFEST.md from the scripts/ tree.

Scans every ``*.py`` under ``scripts/``, takes the first docstring line
as the purpose (falling back to a TODO marker so undocumented scripts
are visible instead of silent), and groups entries by subdirectory with
a criticality tag: ``setup``/``ci``/``safety`` = blocking,
``maintenance``/``debug``/``reports`` = operational, rest = tooling.

``--check`` regenerates in-memory and fails when the committed manifest
is stale — the CI gate that keeps docs and code in lockstep.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCRIPTS = ROOT / "scripts"
MANIFEST = ROOT / "docs" / "SCRIPTS-MANIFEST.md"

_BLOCKING = {"ci", "safety", "setup"}
_OPERATIONAL = {"maintenance", "debug", "reports", "audit", "perf"}


def _purpose(path: Path) -> str:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"))
    except (SyntaxError, UnicodeDecodeError):
        return "⚠ unparsable"
    doc = ast.get_docstring(tree) or ""
    first = doc.strip().splitlines()[0].strip() if doc.strip() else ""
    return first or "⚠ no docstring"


def _criticality(subdir: str) -> str:
    if subdir in _BLOCKING:
        return "blocking"
    if subdir in _OPERATIONAL:
        return "operational"
    return "tooling"


def collect() -> dict[str, list[tuple[str, str, str]]]:
    """Return ``{subdir: [(relpath, purpose, criticality)]}``."""
    groups: dict[str, list[tuple[str, str, str]]] = {}
    for path in sorted(SCRIPTS.rglob("*.py")):
        rel = path.relative_to(ROOT).as_posix()
        if "__pycache__" in rel:
            continue
        subdir = path.relative_to(SCRIPTS).parts[0]
        if subdir.endswith(".py"):  # top-level script
            subdir = "(root)"
        groups.setdefault(subdir, []).append((rel, _purpose(path), _criticality(subdir)))
    return groups


def render(groups: dict[str, list[tuple[str, str, str]]]) -> str:
    total = sum(len(v) for v in groups.values())
    undocumented = sum(1 for v in groups.values() for _, p, _ in v if p.startswith("⚠"))
    lines = [
        "# Scripts Manifest",
        "",
        "Auto-generated by `scripts/ci/generate_scripts_manifest.py` — do",
        "not edit by hand. CI gate: `--check` fails when stale.",
        "",
        f"**{total} scripts** across {len(groups)} groups " f"({undocumented} undocumented).",
        "",
        "| Criticality | Meaning |",
        "|---|---|",
        "| blocking | Runs in CI / setup — breakage blocks the pipeline |",
        "| operational | Runtime ops: maintenance, reports, debug, perf |",
        "| tooling | Dev helpers |",
        "",
    ]
    for subdir in sorted(groups):
        lines.append(f"## `{subdir}` — {groups[subdir][0][2]}")
        lines.append("")
        lines.append("| Script | Purpose |")
        lines.append("|---|---|")
        for rel, purpose, _crit in groups[subdir]:
            lines.append(f"| `{rel}` | {purpose} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if manifest is stale")
    args = ap.parse_args()

    content = render(collect()) + "\n"
    if args.check:
        existing = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
        if existing != content:
            print("SCRIPTS-MANIFEST.md is stale — regenerate with:")
            print("  python scripts/ci/generate_scripts_manifest.py")
            return 1
        print("scripts manifest up to date")
        return 0

    MANIFEST.write_text(content, encoding="utf-8")
    print(f"wrote {MANIFEST} ({content.count('| `scripts/')} entries)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
