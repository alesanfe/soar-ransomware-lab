"""Security response headers middleware.

Applies a hardened header set to EVERY response — including 4xx/5xx
generated by inner middleware — so no code path can leak a response
without the baseline protections:

- ``Strict-Transport-Security`` (configurable — off for plain-HTTP dev)
- ``X-Content-Type-Options: nosniff``
- ``X-Frame-Options: DENY``
- ``Referrer-Policy: no-referrer``
- ``Permissions-Policy`` (browser features off — this is a JSON API)
- ``Content-Security-Policy``: ``default-src 'none'`` everywhere except
  the interactive docs UIs, which get the minimal Swagger/ReDoc CSP.
- ``Cache-Control: no-store`` on API JSON — auth/config responses must
  never be cached by intermediaries.
- Removes the ``Server`` banner.
"""

from starlette.middleware.base import BaseHTTPMiddleware, RequestResponseEndpoint
from starlette.requests import Request
from starlette.responses import Response

__all__ = ["SecurityHeadersMiddleware"]

_DOC_PATHS = ("/docs", "/redoc", "/openapi.json")
# Swagger UI loads its assets from cdn.jsdelivr.net and needs inline
# scripts/styles for the initial page bootstrap.
_DOC_CSP = (
    "default-src 'self' https://cdn.jsdelivr.net; "
    "img-src 'self' data: https://cdn.jsdelivr.net; "
    "style-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; "
    "script-src 'self' 'unsafe-inline' https://cdn.jsdelivr.net; "
    "worker-src 'self' blob:; "
    "frame-ancestors 'none'"
)
_API_CSP = "default-src 'none'; frame-ancestors 'none'"


class SecurityHeadersMiddleware(BaseHTTPMiddleware):
    """Set hardened response headers on every response."""

    def __init__(self, app, hsts_enabled: bool = True) -> None:
        super().__init__(app)
        self._hsts_enabled = hsts_enabled

    async def dispatch(self, request: Request, call_next: RequestResponseEndpoint) -> Response:
        response = await call_next(request)
        headers = response.headers

        headers["X-Content-Type-Options"] = "nosniff"
        headers["X-Frame-Options"] = "DENY"
        headers["Referrer-Policy"] = "no-referrer"
        headers["Permissions-Policy"] = (
            "accelerometer=(), camera=(), geolocation=(), gyroscope=(), "
            "magnetometer=(), microphone=(), payment=(), usb=()"
        )
        if self._hsts_enabled:
            headers["Strict-Transport-Security"] = "max-age=31536000; includeSubDomains"
        if request.url.path.startswith(_DOC_PATHS):
            headers["Content-Security-Policy"] = _DOC_CSP
        else:
            headers["Content-Security-Policy"] = _API_CSP
        if request.url.path.startswith("/api/") or request.url.path.startswith("/auth"):
            headers["Cache-Control"] = "no-store"
        if "server" in headers:
            del headers["server"]
        return response
